/* Generate web copies only. Original photos and certificates are never modified. */
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'assets', 'optimized');
const htmlPath = path.join(root, 'index.html');
const version = 'portfolio-images-v1';

function localPath(src) {
  const resolved = path.resolve(root, src);
  if (!resolved.startsWith(root + path.sep)) throw new Error(`Invalid image path: ${src}`);
  return resolved;
}

async function main() {
  const html = await fs.readFile(htmlPath, 'utf8');
  const sources = new Set();
  const sourceTitles = {};
  for (const match of html.matchAll(/data-cert-title="([^"]+)"[\s\S]*?data-gallery-srcs='([^']+)'/g)) {
    JSON.parse(match[2]).forEach(src => { sourceTitles[src] = match[1]; });
  }
  for (const match of html.matchAll(/data-gallery-srcs='([^']+)'/g)) {
    JSON.parse(match[1]).forEach(src => sources.add(src));
  }
  for (const match of html.matchAll(/<img\b[^>]*>/g)) {
    const original = match[0].match(/data-original-src="([^"]+)"/);
    const src = original || match[0].match(/\bsrc="([^"]+)"/);
    if (src && /^(assets|Certificates)\//.test(src[1])) sources.add(src[1]);
  }

  await fs.mkdir(output, { recursive: true });
  const manifest = {};
  let originalBytes = 0;
  let previewBytes = 0;
  let detailBytes = 0;
  let count = 0;

  // Bound parallelism and libvips threads to avoid overwhelming a laptop.
  sharp.concurrency(2);
  const queue = [...sources].sort();
  async function worker() {
    while (queue.length) {
      const src = queue.shift();
      const input = await fs.readFile(localPath(src));
      const hash = crypto.createHash('sha256').update(version).update(src).update(input).digest('hex').slice(0, 16);
      const certificate = src.includes('เกียรติบัตร') || src.includes('poster');
      const variants = {};
      for (const [name, size, quality] of [['small', 320, 78], ['preview', 640, 82], ['detail', certificate ? 2400 : 1600, certificate ? 89 : 82]]) {
        const filename = `${hash}-${name}.webp`;
        const target = path.join(output, filename);
        try {
          await fs.access(target);
        } catch {
          await sharp(input).rotate().resize({ width: size, height: size, fit: 'inside', withoutEnlargement: true })
            .webp({ quality, effort: 5 }).toFile(target);
        }
        const meta = await sharp(target).metadata();
        variants[name] = { src: `assets/optimized/${filename}`, width: meta.width, height: meta.height, bytes: (await fs.stat(target)).size };
      }
      manifest[src] = variants;
      originalBytes += input.length;
      previewBytes += variants.preview.bytes;
      detailBytes += variants.detail.bytes;
      count++;
      if (count % 20 === 0) console.log(`Optimized ${count}/${sources.size} images`);
    }
  }
  await Promise.all([worker(), worker()]);
  const ordered = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b, 'en')));
  await fs.writeFile(path.join(output, 'manifest.json'), JSON.stringify(ordered, null, 2) + '\n');
  await fs.writeFile(path.join(output, 'manifest.js'), `/* Generated by scripts/optimize-images.cjs */\nwindow.PORTFOLIO_IMAGES = ${JSON.stringify(ordered)};\n`);

  if (process.argv.includes('--update-html')) {
    let updated = html.replace(/<div class="ach-cert-image"\s+style="background-image: url\('([^']+)'\);">\s*<\/div>/g, (_, src) => {
      const image = manifest[src];
      if (!image) throw new Error(`Missing cover: ${src}`);
      return `<div class="ach-cert-image">\n            <img data-original-src="${src}" src="${image.preview.src}" srcset="${image.small.src} ${image.small.width}w, ${image.preview.src} ${image.preview.width}w" sizes="(max-width: 768px) calc((100vw - 52px) / 2), (max-width: 1024px) 45vw, 370px" width="${image.preview.width}" height="${image.preview.height}" alt="เกียรติบัตร" loading="lazy" decoding="async">\n          </div>`;
    });
    // Idempotently update normal images and covers after future source additions.
    updated = updated.replace(/<img\b[^>]*>/g, tag => {
      const original = tag.match(/data-original-src="([^"]+)"/) || tag.match(/\bsrc="([^"]+)"/);
      const src = original?.[1];
      const image = manifest[src];
      if (!image) return tag;
      const hero = src === 'assets/profile.jpg';
      const logo = /logo/.test(src);
      const selected = hero ? image.detail : logo ? image.small : image.preview;
      let result = tag.replace(/\s(?:src|srcset|sizes|width|height|loading|decoding|fetchpriority|data-original-src)="[^"]*"/g, '');
      if (src.startsWith('Certificates/') && sourceTitles[src]) {
        const alt = `เกียรติบัตร ${sourceTitles[src]}`.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
        result = result.replace(/\balt="[^"]*"/, `alt="${alt}"`);
      }
      const attrs = ` data-original-src="${src}" src="${selected.src}" width="${selected.width}" height="${selected.height}" decoding="async" loading="${hero || logo ? 'eager' : 'lazy'}"`;
      const responsive = !hero && !logo && !tag.includes('poster-full-img')
        ? ` srcset="${image.small.src} ${image.small.width}w, ${image.preview.src} ${image.preview.width}w" sizes="${src.startsWith('Certificates/') ? '(max-width: 768px) calc((100vw - 52px) / 2), (max-width: 1024px) 45vw, 370px' : '(max-width: 768px) 85vw, 440px'}"`
        : '';
      result = result.replace(/\s*\/?\s*>$/, `${attrs}${responsive}${hero ? ' fetchpriority="high"' : ''}>`);
      return result;
    });
    await fs.writeFile(htmlPath, updated);
  }
  console.log(JSON.stringify({ images: count, originalBytes, previewBytes, detailBytes }, null, 2));
}

main().catch(error => { console.error(error); process.exitCode = 1; });
